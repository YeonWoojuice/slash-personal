-- ---------------------------------------------------------------------------
-- V010 : 기기 작업 수신 여부 (W1-03)
--
--   사용자가 PC 를 등록해 둔 채로 "지금은 작업을 받지 말라"고 정할 수 있게 한다.
--   연결 해제(REVOKED)와 다르다 — 연결은 그대로 유지하고 되돌릴 수 있다.
--
--   status 에 값을 더하지 않고 열을 따로 두는 이유:
--     연결 상태(ONLINE·READY·BUSY·OFFLINE)와 "작업을 받을지"는 서로 다른 축이다.
--     한 열에 섞으면 "정지 중인데 연결이 끊겼다" 같은 조합마다 값을 쪼개야 하고,
--     정지 중 연결이 끊기면 OFFLINE 이 덮어써서 사용자가 꺼 둔 설정이 사라진다.
-- ---------------------------------------------------------------------------

ALTER TABLE devices
    -- 등록하면 받는 것이 기본이다. 사용자가 끄기 전까지는 지금까지와 동작이 같다.
    ADD COLUMN accepting_tasks boolean NOT NULL DEFAULT true;

COMMENT ON COLUMN devices.accepting_tasks
    IS '사용자가 새 작업 수신을 켜 둔 상태인지. 거짓이면 연결돼 있어도 작업을 보내지 않는다.';
